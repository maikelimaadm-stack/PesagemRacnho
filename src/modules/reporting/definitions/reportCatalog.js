import { PESAGENS_POR_LOTE, PESAGENS_POR_PERIODO, PESAGENS_POR_SESSAO } from './pesagens.js';
import { REBANHO_INVENTARIO, REBANHO_POR_DIMENSAO, REBANHO_SEM_PESAGEM } from './rebanho.js';
import {
  COMERCIAL_ABATES, COMERCIAL_COMPRAS, COMERCIAL_VENDAS, EMBARQUES_ROMANEIO, FECHAMENTO_DIA, LOTES_OCUPACAO, MORTES_CATEGORIA, MORTES_CAUSA, MORTES_LOTE,
  MORTES_PERIODO, MOV_ENTRADAS_SAIDAS, MOV_MUDANCAS_LOTE, MOV_PERMANENCIAS, PESAGENS_ORIGEM, PESAGENS_PENDENCIAS, PESAGENS_POR_OPERADOR, SAIDAS_MOTIVO,
} from './operacional.js';
import {
  CADASTROS_RELATORIOS, CADASTROS_USUARIOS, CONTROLE_AUDITORIA, CONTROLE_BACKUPS, CONTROLE_QUALIDADE, EMBARQUES_PREVISTO_REALIZADO, RELATORIOS_BLOQUEADOS,
} from './controle.js';
import { DESEMPENHO_FAIXA_PESO, DESEMPENHO_INDIVIDUAL, DESEMPENHO_PERDENDO_PESO, DESEMPENHO_POR_DIMENSAO, DESEMPENHO_POR_LOTE } from './desempenho.js';

const DEFINITIONS = [
  PESAGENS_POR_PERIODO,
  PESAGENS_POR_SESSAO,
  PESAGENS_POR_LOTE,
  REBANHO_INVENTARIO,
  ...REBANHO_POR_DIMENSAO,
  REBANHO_SEM_PESAGEM,
  DESEMPENHO_INDIVIDUAL,
  DESEMPENHO_POR_LOTE,
  ...DESEMPENHO_POR_DIMENSAO,
  DESEMPENHO_PERDENDO_PESO,
  DESEMPENHO_FAIXA_PESO,
  PESAGENS_POR_OPERADOR,
  PESAGENS_PENDENCIAS,
  PESAGENS_ORIGEM,
  LOTES_OCUPACAO,
  MOV_ENTRADAS_SAIDAS,
  MOV_MUDANCAS_LOTE,
  MOV_PERMANENCIAS,
  SAIDAS_MOTIVO,
  MORTES_PERIODO,
  MORTES_CAUSA,
  MORTES_CATEGORIA,
  MORTES_LOTE,
  COMERCIAL_VENDAS,
  COMERCIAL_ABATES,
  COMERCIAL_COMPRAS,
  EMBARQUES_ROMANEIO,
  EMBARQUES_PREVISTO_REALIZADO,
  FECHAMENTO_DIA,
  CONTROLE_AUDITORIA,
  CONTROLE_QUALIDADE,
  CONTROLE_BACKUPS,
  ...CADASTROS_RELATORIOS,
  CADASTROS_USUARIOS,
  ...RELATORIOS_BLOQUEADOS,
];

const BY_ID = new Map();
for (const definition of DEFINITIONS) {
  if (BY_ID.has(definition.id)) throw new Error(`catálogo: relatório duplicado (${definition.id})`);
  BY_ID.set(definition.id, definition);
}

export function listReportDefinitions() {
  return [...DEFINITIONS];
}

export function getReportDefinition(id) {
  return BY_ID.get(id) ?? null;
}
